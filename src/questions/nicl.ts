function numberReason(
  topic: string,
  stem: string,
  correct: number,
  explanation: string,
  seconds: number,
) {
  add(
    "Reasoning",
    topic,
    stem,
    String(correct),
    [0, 1, 2, 3, 4, 5, 6]
      .filter((n) => n !== correct)
      .slice(0, 4)
      .map(String),
    explanation,
    seconds,
  );
}

