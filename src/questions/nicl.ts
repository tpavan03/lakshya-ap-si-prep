// Authored practice, not reconstructed or claimed to be an official NICL paper.
// Each set repeats its complete data in the stem, so a single selected item is solvable.
const bank: Question[] = [];
const format = (n: number) =>
  Number.isInteger(n)
    ? String(n)
    : n.toFixed(2).replace(/0+$/, "").replace(/\.$/, "");
const money = (n: number) => `₹${format(n)}`;
function add(
  subject: Subject,
  topic: string,
  stem: string,
  correct: string,
  others: string[],
  explanation: string,
  seconds = 75,
  difficulty: Question["difficulty"] = "Hard",
) {
  const id = `nicl-${String(bank.length + 1).padStart(4, "0")}`;
  const options = [...new Set([correct, ...others])].slice(0, 5);
  if (options.length < 4)
    throw new Error(`Insufficient distinct choices: ${id}`);
  const shift = bank.length % options.length;
  options.push(...options.splice(0, shift));
  bank.push({
    id,
    subject,
    topic,
    question: stem,
    options,
    answer: options.indexOf(correct),
    explanation,
    hint: explanation.split(". ")[0],
    seconds,
    difficulty,
    source: "Original NICL AO practice · editorial, not a PYQ",
    exam: "NICL AO Generalist",
  });
}
function number(
  topic: string,
  stem: string,
  correct: number,
  explanation: string,
  unit = "",
  step = 5,
  seconds = 90,
) {
  add(
    "Arithmetic",
    topic,
    stem,
    `${format(correct)}${unit}`,
    [
      correct + step,
      correct - step,
      correct + 2 * step,
      correct + 3 * step,
    ].map((n) => `${format(n)}${unit}`),
    explanation,
    seconds,
  );
}

